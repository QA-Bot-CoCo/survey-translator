"""Create a wheel-only hash lock from pip's --dry-run --report JSON."""
import argparse
import json
from pathlib import Path
from urllib.request import Request, urlopen


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("report", type=Path)
    parser.add_argument("--output", type=Path, default=Path("requirements.txt"))
    args = parser.parse_args()
    packages = json.loads(args.report.read_text(encoding="utf-8"))["install"]
    queries = [
        {"package": {"name": item["metadata"]["name"], "ecosystem": "PyPI"},
         "version": item["metadata"]["version"]}
        for item in packages
    ]
    request = Request(
        "https://api.osv.dev/v1/querybatch",
        data=json.dumps({"queries": queries}).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urlopen(request, timeout=30) as response:
        results = json.load(response)["results"]
    findings = [
        (query["package"]["name"], [v["id"] for v in result.get("vulns", [])])
        for query, result in zip(queries, results) if result.get("vulns")
    ]
    if findings:
        raise SystemExit(f"Resolve advisories before locking: {findings}")
    lines = [
        "# Generated by tools/lock_dependencies.py; do not edit individual hashes.",
        "--require-hashes", "--only-binary=:all:", "",
    ]
    for query in sorted(queries, key=lambda item: item["package"]["name"].lower()):
        name, version = query["package"]["name"], query["version"]
        with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
            release = json.load(response)
        hashes = sorted({
            artifact["digests"]["sha256"] for artifact in release["urls"]
            if artifact["packagetype"] == "bdist_wheel" and not artifact["yanked"]
        })
        if not hashes:
            raise SystemExit(f"No non-yanked wheels for {name} {version}")
        lines.append(f"{name}=={version} \\")
        for index, digest in enumerate(hashes):
            suffix = " \\" if index < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{digest}{suffix}")
        lines.append("")
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Locked {len(queries)} packages; no OSV matches at generation time.")


if __name__ == "__main__":
    main()
